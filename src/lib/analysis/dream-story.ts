        "한 존재와 눈을 맞춘 장면은 개별적인 관계에 시선이 모입니다. 무리를 본 장면은 대상 하나보다 공간 전체의 움직임과 규모가 더 중요할 수 있습니다. 한 송이와 꽃밭 역시 같은 꽃이라도 다른 만남입니다.",
