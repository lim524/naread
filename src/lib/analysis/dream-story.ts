        "발견한 것과 가까이 간 것, 실제로 접촉한 것은 서로 다른 단계입니다. 자신이 어느 단계에 있었는지를 분리하면 꿈의 이야기를 필요 이상으로 부풀리지 않으면서도 더 구체적으로 읽을 수 있습니다.",
