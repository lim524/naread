export function datasetFortune(date: string, seed: string): Fortune {
  let value = 2166136261;
  for (const ch of date + seed)
    value = Math.imul(value ^ ch.charCodeAt(0), 16777619) >>> 0;
  const prompt = dailyPrompts[value % dailyPrompts.length];
  return {
    ...prompt,
    color: [
      "연한 청록",
      "따뜻한 살구",
      "부드러운 황토",
      "은빛 회색",
      "옅은 남색",
    ][value % 5],
    number: (value % 99) + 1,
  };
}
